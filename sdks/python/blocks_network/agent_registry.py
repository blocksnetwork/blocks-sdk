@dataclass
class AgentScaling:
    """Scaling configuration for multi-instance support."""

    expected_instances: int
    concurrency: int
    max_pending_backlog: Optional[int] = None    # Default: 10 (applied at read time by On Interval function)
    max_running_time_sec: Optional[int] = None   # No default (if unset, stuck-running detection is skipped)


@dataclass
class AgentCard:
    """Agent card payload (new 9-section structure) -- authored by developers in agent-card.json.

    Required sections: identity, capabilities, tags, runtime.
    Optional sections: io, streams, security, services, extensions.

    ``display_name`` and ``agent_name`` are convenience fields that map to
    ``identity.displayName`` and ``identity.agentName`` in the wire format.
    They are serialized into the identity dict by ``_card_to_dict``.
    """

    display_name: str = ""
    agent_name: str = ""
    identity: Dict[str, Any] = field(default_factory=dict)
    capabilities: Dict[str, Any] = field(default_factory=dict)
    tags: List[Dict[str, Any]] = field(default_factory=list)
    runtime: Dict[str, Any] = field(default_factory=dict)
    io: Optional[Dict[str, Any]] = None
    streams: Optional[Dict[str, Any]] = None
    security: Optional[Dict[str, Any]] = None
    services: Optional[Dict[str, Any]] = None
    extensions: Optional[Dict[str, Any]] = None


@dataclass
class OutputAgentCard:
    """Agent card payload (output/public schema) -- served by the API.

    Same as AgentCard minus the runtime section.
    """

    identity: Dict[str, Any] = field(default_factory=dict)
    capabilities: Optional[Dict[str, Any]] = None
    tags: Optional[List[Dict[str, Any]]] = None
    io: Optional[Dict[str, Any]] = None
    streams: Optional[Dict[str, Any]] = None
    security: Optional[Dict[str, Any]] = None
    services: Optional[Dict[str, Any]] = None
    extensions: Optional[Dict[str, Any]] = None


@dataclass
class AgentEntry:
    """Agent entry returned from registry queries.

    ``listing`` carries the server-side visibility tier; valid values are
    ``'private' | 'public'`` (typed as ``Optional[str]`` for dataclass
    defensiveness against unknown server values).

    ``billing_mode`` is the server-derived billing tier used by the SDK
    to select the PubNub keyset: ``'paid'`` routes to the network keyset,
    ``'free'`` (or missing) routes to the playground keyset.
    """

    agent_name: str
    name: str
    description: Optional[str] = None
    tags: Optional[List[Any]] = None
    scaling: Optional[Any] = None
    card: Optional[Any] = None
    card_ref: Optional[str] = None
    card_summary: Optional[str] = None
    listing: Optional[str] = None
    billing_mode: Optional[Literal["free", "paid"]] = None
    created_at: Optional[str] = None
    updated_at: Optional[str] = None


@dataclass
class ConnectAgentOptions:
    """Options for registering an agent.

    instance_id is auto-generated by start_agent_instance, not caller-supplied.

    ``listing`` valid values are ``'private' | 'public'`` (typed as
    ``Optional[str]`` for dataclass defensiveness). When omitted, the
    server applies its default (``'public'``).

    ``billing_mode`` is REQUIRED on the wire — the backend connect Zod
    schema requires it (Billing Mode Contract Phase 2). It is populated
    by ``start_agent_instance`` from the registry GET at boot; there is
    no provider-supplied override path. Typed as
    ``Optional[Literal['free', 'paid']]`` for dataclass defaulting only;
    in practice every real call sets it.
    """

    instance_id: Optional[str] = None
    description: Optional[str] = None
    # AgentTag objects ({id, name, description?, examples?}), matching Node
    # ConnectAgentOptions.tags: AgentTag[]. (The pre-rename `skills` field was
    # List[str] here, which diverged from Node; the rename aligns the shape.)
    tags: Optional[List[Dict[str, Any]]] = None
    scaling: Optional[AgentScaling] = None
    card: Optional[Union[AgentCard, Dict[str, Any]]] = None
    card_ref: Optional[str] = None
    card_summary: Optional[str] = None
    listing: Optional[str] = None
    billing_mode: Optional[Literal["free", "paid"]] = None
    supported_task_kinds: Optional[List[str]] = None
    actor: Optional[str] = None
    request_id: Optional[str] = None
    base_url: Optional[str] = None
    agent_auth: Optional[Any] = None  # AgentAuth instance for API key-based auth


