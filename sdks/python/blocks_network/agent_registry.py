@dataclass
class ConnectAgentResult:
    """Result of registering an agent."""

    pam_token: Optional[str] = None
    agent_id: Optional[str] = None
    control_channel: Optional[str] = None


def _assert_no_legacy_skills_field(card: Optional[Union[AgentCard, Dict[str, Any]]]) -> None:
    """Reject the legacy ``skills`` field on an agent-card dict.

    ``skills`` was renamed to ``tags``; there is no wire/SDK alias. Without
    this guard, Python callers who still pass ``{"skills": [...]}`` would
    silently send the field over the wire and only see the backend's
    generic rejection. This fails fast on the client side with an
    actionable error.
    """
    if card is None:
        return
    if isinstance(card, dict) and "skills" in card:
        raise ValueError(
            "[blocks-network] agent-card field `skills` was renamed to `tags`. "
            "Action: rename the field in your code (or in any agent-card.json you load) — "
            "same shape, only the key name changes. This SDK ships no compatibility alias. "
            "If you publish via `blocks-cli`, upgrading the CLI rewrites the field for you, "
            "but programmatic callers (this SDK) must rename."
        )


def connect_agent(
    agent_name: str,
    options: Optional[ConnectAgentOptions] = None,
) -> ConnectAgentResult:
    """
    Register or update an agent in the registry.

    Sends a POST request to the dedicated registry endpoint which handles
    all registry metadata operations (UUID metadata, memberships, audit events)
    server-side.

    Args:
        agent_name: The agent name identifier.
        options: Registration options including instance_id, card, etc.

    Returns:
        ConnectAgentResult with optional pamToken from the server.
    """
    if not re.fullmatch(r'[a-zA-Z0-9_]+', agent_name):
        raise ValueError(
            "agent_name must contain only alphanumeric characters "
            "and underscores (no hyphens)"
        )

    if options is None:
        options = ConnectAgentOptions()

    _assert_no_legacy_skills_field(options.card)

    cli_version = os.environ.get("BLOCKS_CLI_VERSION") or None

    result_holder: Dict[str, Any] = {}
    agent_auth = options.agent_auth

    if agent_auth is None:
        raise RuntimeError(
            "[AgentRegistry] agent_auth is required. "
            "Set BLOCKS_API_KEY and pass agent_auth to connect_agent."
        )

    # Connect payload: runtime-only fields for /auth/agent/connect.
    # Card, description, cardRef, cardSummary, and tags are sent
    # by `blocks publish`, not by the SDK at connect time.
    #
    # ``billingMode`` is the registry-resolved value forwarded by
    # ``start_agent_instance``. Backend connect Zod schema (Billing Mode
    # Contract Phase 2) requires it; the SDK does not derive or override
    # the value from anywhere except the registry GET.
    payload = {
        "agentName": agent_name,
        "instanceId": options.instance_id,
        "billingMode": options.billing_mode,
        "listing": options.listing,
        "expectedInstances": options.scaling.expected_instances if options.scaling else None,
        "concurrency": options.scaling.concurrency if options.scaling else None,
        "maxPendingBacklog": options.scaling.max_pending_backlog if options.scaling else None,
        "maxRunningTimeSec": options.scaling.max_running_time_sec if options.scaling else None,
        "deviceOs": _detect_device_os(),
        "sdkLanguage": _SDK_LANGUAGE,
        "sdkVersion": SDK_VERSION,
        "protocolVersions": list(SUPPORTED_PROTOCOL_VERSIONS),
        "preferredProtocolVersion": CURRENT_PROTOCOL_VERSION,
        "cliVersion": cli_version,
    }
    # Strip None values -- backend Zod schema treats null as invalid for optional fields
    payload = {k: v for k, v in payload.items() if v is not None}

    def _do_auth_register() -> None:
        from .agent_auth import AgentAuthFatalError

        try:
            resp_data = agent_auth.init(registration_payload=payload)
            if isinstance(resp_data, dict):
                result_holder.update(resp_data)
        except AgentAuthFatalError:
            raise
        except Exception as exc:
            raise RuntimeError(f"[AgentRegistry] Registration failed: {exc}") from exc

    with_retry(_do_auth_register)

    pam_token = result_holder.get("pamToken")
    agent_id = result_holder.get("agentId")
    control_channel = result_holder.get("controlChannel")
    return ConnectAgentResult(
        pam_token=pam_token if isinstance(pam_token, str) else None,
        agent_id=agent_id if isinstance(agent_id, str) else None,
        control_channel=control_channel if isinstance(control_channel, str) else None,
    )


def get_agent(
    agent_name: str,
    base_url: Optional[str] = None,
    api_key: Optional[str] = None,
) -> Optional[AgentEntry]:
    """
    Get a single agent by name.

    Pass ``api_key`` to authenticate the lookup. Without it, the registry
    endpoint returns 404 for private agents (existence-privacy) and the SDK
    cannot resolve its own published record — leaving keyset routing stranded
    on the playground default while connect mints a PAM token for the network
    keyset.

    Args:
        agent_name: The agent name identifier to look up.
        base_url: Optional base URL override.
        api_key: Optional Blocks API key for authenticated lookup of private agents.

    Returns:
        AgentEntry if found, None otherwise.
    """
    url = _registry_url(query={"agentName": agent_name}, base_url=base_url)
    headers = {"Authorization": f"Bearer {api_key}"} if api_key else None

    result = with_retry(lambda: _registry_fetch(url, headers=headers))

    if result is None:
        return None

    agent = result.get("agent")
    if not agent:
        return None

    return _map_server_agent_to_entry(agent)


def fetch_agent_registry(
    limit: int = 100,
    cursor: Optional[str] = None,
    base_url: Optional[str] = None,
) -> AgentRegistryResult:
    """
    Fetch the agent registry (all agents).

    Args:
        limit: Maximum number of agents to return (default 100).
        cursor: Pagination cursor for fetching next page.
        base_url: Optional base URL override.

    Returns:
        AgentRegistryResult with the list of agents.
    """
    query: Dict[str, str] = {"include": "full"}
    if limit:
        query["limit"] = str(limit)
    if cursor:
        query["cursor"] = cursor

    url = _registry_url(query, base_url=base_url)

    result = with_retry(lambda: _registry_fetch(url))

    if result is None:
        return AgentRegistryResult(agents=[], total_count=0)

    agents = [_map_server_agent_to_entry(a) for a in result.get("agents", [])]
    return AgentRegistryResult(
        agents=agents,
        next=result.get("next"),
        total_count=result.get("totalCount"),
    )


