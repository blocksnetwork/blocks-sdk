# Transient error indicators for Python network exceptions
_TRANSIENT_ERROR_INDICATORS = (
    "Name or service not known",
    "getaddrinfo failed",
    "Connection refused",
    "Connection reset",
    "timed out",
    "NetworkIssues",
)


def _detect_device_os() -> str:
    try:
        return platform.system().lower()
    except Exception:
        return "unknown"


_SDK_LANGUAGE = "Python"


def with_retry(
    fn: Callable[[], T],
    max_retries: int = 3,
    base_delay_ms: int = 500,
) -> T:
    """
    Retry helper for transient network errors (DNS failures, timeouts, etc.).

    Implements exponential backoff with jitter, matching the Node implementation.
    """
    last_error: Optional[Exception] = None

    for attempt in range(max_retries):
        try:
            return fn()
        except Exception as err:
            last_error = err
            error_str = str(err)
            is_transient = any(
                indicator in error_str for indicator in _TRANSIENT_ERROR_INDICATORS
            )

            if not is_transient or attempt == max_retries - 1:
                raise

            delay_s = (base_delay_ms * (2 ** attempt) + random.random() * 100) / 1000.0
            time.sleep(delay_s)

    # Should not reach here, but satisfy type checker
    raise last_error  # type: ignore[misc]


def _card_to_dict(card: Union[AgentCard, Dict[str, Any], None]) -> Optional[Dict[str, Any]]:
    """Convert an AgentCard dataclass or dict to a plain dict for JSON serialization."""
    if card is None:
        return None
    if isinstance(card, dict):
        return card
    # Build identity dict with displayName and agentName
    identity = dict(card.identity)
    if card.display_name:
        identity["displayName"] = card.display_name
    if card.agent_name:
        identity["agentName"] = card.agent_name
    # Convert dataclass to dict (new 9-section structure)
    result: Dict[str, Any] = {
        "identity": identity,
        "capabilities": card.capabilities,
        "tags": card.tags,
        "runtime": card.runtime,
    }
    if card.io is not None:
        result["io"] = card.io
    if card.streams is not None:
        result["streams"] = card.streams
    if card.security is not None:
        result["security"] = card.security
    if card.services is not None:
        result["services"] = card.services
    if card.extensions is not None:
        result["extensions"] = card.extensions
    return result


