def _map_server_agent_to_entry(agent: Dict[str, Any]) -> AgentEntry:
    """Map server JSON response to an AgentEntry."""
    return AgentEntry(
        agent_name=agent.get("agentName", ""),
        name=agent.get("name") or agent.get("agentName", ""),
        description=agent.get("description"),
        tags=agent.get("tags"),
        scaling=agent.get("scaling"),
        card=agent.get("card"),
        card_ref=agent.get("cardRef"),
        card_summary=agent.get("cardSummary"),
        listing=agent.get("listing"),
        billing_mode=agent.get("billingMode"),
        created_at=agent.get("registeredAt"),
    )


