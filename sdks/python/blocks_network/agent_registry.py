def _get_base_url(override_url: Optional[str] = None) -> str:
    """Resolve the backend base URL from an explicit override."""
    if override_url:
        return override_url.rstrip("/")
    raise ValueError("[AgentRegistry] baseUrl is required: provide it via options or CDM config")


def _registry_url(
    query: Optional[Dict[str, str]] = None,
    base_url: Optional[str] = None,
) -> str:
    """Build a registry REST endpoint URL."""
    from urllib.parse import urlencode

    url = f"{_get_base_url(base_url)}/api/v1/registry/agents"
    if query:
        filtered = {k: v for k, v in query.items() if v}
        if filtered:
            url += "?" + urlencode(filtered)
    return url


def _registry_fetch(
    url: str,
    method: str = "GET",
    body: Optional[bytes] = None,
    headers: Optional[Dict[str, str]] = None,
) -> Optional[Any]:
    """
    Perform an HTTP request to the registry endpoint.

    Returns parsed JSON on success, None on 404, raises on other errors.
    """
    import ssl
    import urllib.request
    import urllib.error

    import certifi

    ssl_ctx = ssl.create_default_context(cafile=certifi.where())
    default_headers = {PROTOCOL_VERSION_HEADER: CURRENT_PROTOCOL_VERSION}
    if headers:
        default_headers.update(headers)
    inject_affinity(default_headers)
    req = urllib.request.Request(
        url,
        data=body,
        headers=default_headers,
        method=method,
    )

    try:
        with urllib.request.urlopen(req, context=ssl_ctx, timeout=30) as resp:
            capture_affinity(resp)
            resp_body = resp.read().decode("utf-8")
            if not resp_body:
                return {}
            return json.loads(resp_body)
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return None
        resp_body = exc.read().decode("utf-8") if exc.fp else ""
        message = f"HTTP {exc.code}"
        try:
            err_json = json.loads(resp_body)
            if isinstance(err_json, dict) and err_json.get("message"):
                message = err_json["message"]
        except (json.JSONDecodeError, ValueError):
            pass
        raise RuntimeError(f"[AgentRegistry] Request failed: {message}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"[AgentRegistry] Request failed: {exc.reason}") from exc
    except OSError as exc:
        raise RuntimeError(f"[AgentRegistry] Request failed: {exc}") from exc


